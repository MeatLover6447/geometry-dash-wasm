import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync,gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {patchAssets} from '../patches/native-streaming.mjs';
import {patchDownloadedAudio} from '../patches/downloaded-audio.mjs';
import {patchWasm} from '../patches/reduced-area-colors.mjs';
import {patchAffine} from '../patches/affine-transform.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const hash=value=>createHash('sha256').update(value).digest('hex');
const upstream=JSON.parse(fs.readFileSync(path.join(root,'upstream/manifest.json'),'utf8'));
const previous=JSON.parse(fs.readFileSync(path.join(root,'dist/gd_assets.json'),'utf8'));
const original=gunzipSync(fs.readFileSync(path.join(root,'upstream/loader.gz')));
assert.equal(hash(original),upstream.loader.sha256,'Upstream loader integrity');
const originalAssets=fs.readFileSync(path.join(root,'upstream/gd_assets.js'),'utf8');
assert.equal(hash(originalAssets),upstream.supportFiles['gd_assets.js'],'Upstream asset loader integrity');
const runtime=patchDownloadedAudio(original);
const packed=gzipSync(runtime,{level:9});
const assets=patchAssets(originalAssets);
const loader={url:`payload/loader-${hash(runtime).slice(0,24)}.gz`,size:runtime.length,compressedSize:packed.length,sha256:hash(runtime)};
const {output:engine}=patchAffine(patchWasm(gunzipSync(fs.readFileSync(path.join(root,'upstream/wasm.gz')))).output);
const compressedEngine=gzipSync(engine,{level:9}),engineHash=hash(engine);
const wasm={url:`payload/wasm-${engineHash.slice(0,24)}.gz`,size:engine.length,compressedSize:compressedEngine.length,sha256:engineHash,nativeUrl:`/engine/${engineHash}.wasm`};
const manifest={...upstream,upstreamBuild:upstream.build,loader,wasm,supportFiles:{...upstream.supportFiles,'gd_assets.js':hash(assets)}};
manifest.wrapperSourceSha256=hash(fs.readFileSync(path.join(root,'dist/index.html'),'utf8').replaceAll(previous.build,'__GD_BUILD__'));
manifest.build=hash(JSON.stringify(manifest)).slice(0,24);
fs.writeFileSync(path.join(root,'dist',loader.url),packed);
fs.writeFileSync(path.join(root,'dist',wasm.url),compressedEngine);
fs.writeFileSync(path.join(root,'dist/gd_assets.js'),assets);
const index=path.join(root,'dist/index.html');
fs.writeFileSync(index,fs.readFileSync(index,'utf8').replaceAll(previous.build,manifest.build));
fs.writeFileSync(path.join(root,'dist/gd_assets.json'),JSON.stringify(manifest));
if(previous.loader.url!==loader.url&&/^payload\/loader-[a-f0-9]+\.gz$/.test(previous.loader.url))fs.unlinkSync(path.join(root,'dist',previous.loader.url));
if(previous.wasm.url!==wasm.url&&/^payload\/wasm-[a-f0-9]+\.gz$/.test(previous.wasm.url))fs.unlinkSync(path.join(root,'dist',previous.wasm.url));
console.log(`Built ${manifest.build}: streaming, downloaded audio, optional area colors, and compact affine transforms. Full game data preserved.`);
